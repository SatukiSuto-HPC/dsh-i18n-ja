// Build lib/client.js for dsh-i18n-ja from out/ja/*.json, validating against
// the extracted en dictionaries first.
import fs from "node:fs";
import path from "node:path";

const locales = JSON.parse(fs.readFileSync("out/locales.json", "utf8"));
const jaDicts = {};
let errors = 0, warnings = 0;
const ph = s => (s.match(/\{[A-Za-z0-9_]+\}/g) ?? []).sort().join(",");

for (const rec of locales) {
  const en = rec.dicts.en ?? {};
  const file = `out/ja/${rec.ns}.json`;
  if (!fs.existsSync(file)) { console.error(`MISSING translation file: ${file}`); errors++; continue; }
  let ja;
  try { ja = JSON.parse(fs.readFileSync(file, "utf8")); }
  catch (e) { console.error(`BAD JSON ${file}: ${e.message}`); errors++; continue; }
  const enKeys = Object.keys(en), jaKeys = Object.keys(ja);
  const missing = enKeys.filter(k => !(k in ja));
  const extra = jaKeys.filter(k => !(k in en));
  if (missing.length) { console.warn(`WARN ${rec.ns}: ${missing.length} keys missing in ja (will fall back to en): ${missing.slice(0, 10).join(", ")}`); warnings++; }
  if (extra.length) { console.warn(`WARN ${rec.ns}: ${extra.length} extra keys dropped: ${extra.slice(0, 10).join(", ")}`); warnings++; }
  const clean = {};
  for (const k of enKeys) {
    const v = ja[k];
    if (typeof v !== "string" || !v.trim()) { console.warn(`WARN ${rec.ns}.${k}: empty/non-string ja value, dropped`); warnings++; continue; }
    if (ph(en[k]) !== ph(v)) { console.error(`ERROR ${rec.ns}.${k}: placeholder mismatch\n  en: ${en[k]}\n  ja: ${v}`); errors++; continue; }
    clean[k] = v;
  }
  jaDicts[rec.ns] = clean;
}

if (errors) { console.error(`build aborted: ${errors} errors, ${warnings} warnings`); process.exit(1); }

const total = Object.values(jaDicts).reduce((n, d) => n + Object.keys(d).length, 0);
const json = JSON.stringify(jaDicts, null, "\t").replace(/\n\t*/g, m => "\n" + m.trim());
const out = `window.__ModuleLoader__.load({
\tid: "dsh-i18n-ja",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
\t\t//#region ja dictionaries (generated by tools/build-client.mjs from out/ja/*.json)
\t\tconst jaDictionaries = ${json};
\t\tconst JA_LANGUAGE = { id: "ja", label: "日本語", fallback: "en" };
\t\tconst inject = ["locale"];
\t\t/**
\t\t* Apply the 日本語 language pack: register the language in the locale
\t\t* catalog, then register each namespace's ja dictionary independently so
\t\t* one duplicate/conflict never blocks the rest.
\t\t*/
\t\tfunction apply(ctx) {
\t\t\tctx.effect(() => {
\t\t\t\tconst disposers = [];
\t\t\t\ttry {
\t\t\t\t\tdisposers.push(ctx.locale.addLanguage(JA_LANGUAGE));
\t\t\t\t} catch {}
\t\t\t\tfor (const [ns, dict] of Object.entries(jaDictionaries)) try {
\t\t\t\t\tdisposers.push(ctx.locale.register(ns, JA_LANGUAGE.id, dict));
\t\t\t\t} catch {}
\t\t\t\treturn () => {
\t\t\t\t\tfor (const dispose of disposers) dispose();
\t\t\t\t};
\t\t\t}, "dsh-i18n-ja: ja language pack");
\t\t}
\t\texports.JA_LANGUAGE = JA_LANGUAGE;
\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t}
});
`;
fs.mkdirSync("lib", { recursive: true });
fs.writeFileSync("lib/client.js", out, "utf8");
console.log(`built lib/client.js: ${Object.keys(jaDicts).length} namespaces, ${total} ja keys, ${warnings} warnings`);
